"""Step 2 - run the SQL data quality checks and write a report.

Input : data/processed/sales_long.parquet, sql/data_quality_checks.sql
Output: reports/data_quality.md, reports/figures/daily_sales.png,
        reports/figures/zero_share_by_dept.png
Run   : python src/data_quality.py
"""
import re

import duckdb
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from config import FIGURES, PROCESSED, REPORTS, ROOT, STORE  # noqa: E402

MAX_ROWS = 15


def load_checks(path):
    """Split the .sql file into (name, description, query) using the '-- name:' markers."""
    text = path.read_text(encoding="utf-8")
    parts = re.split(r"^-- name:\s*(.+)$", text, flags=re.M)
    checks = []
    for name, body in zip(parts[1::2], parts[2::2]):
        lines = body.strip().splitlines()
        desc = lines[0][2:].strip() if lines and lines[0].startswith("--") else ""
        checks.append((name.strip(), desc, body.strip()))
    return checks


def to_markdown(df):
    """Small markdown table writer (no extra packages needed)."""
    if df.empty:
        return "_No rows: nothing to flag._"
    shown = df.head(MAX_ROWS).astype(object).where(df.head(MAX_ROWS).notna(), "")
    lines = ["| " + " | ".join(map(str, df.columns)) + " |",
             "| " + " | ".join("---" for _ in df.columns) + " |"]
    lines += ["| " + " | ".join(map(str, row)) + " |" for row in shown.itertuples(index=False)]
    if len(df) > MAX_ROWS:
        lines.append(f"\n_Showing {MAX_ROWS} of {len(df)} rows._")
    return "\n".join(lines)


def main():
    parquet = (PROCESSED / "sales_long.parquet").as_posix()
    con = duckdb.connect()
    con.execute(f"CREATE VIEW sales AS SELECT * FROM read_parquet('{parquet}')")

    report = [f"# Data quality report - Walmart store {STORE}", "",
              "Generated by `src/data_quality.py` from the checks in `sql/data_quality_checks.sql`.", ""]
    for name, desc, query in load_checks(ROOT / "sql" / "data_quality_checks.sql"):
        result = con.execute(query).df()
        print(f"\n== {name}\n{result.head(MAX_ROWS).to_string(index=False)}")
        report += [f"## {name}", "", desc, "", to_markdown(result), ""]

    # Figure 1: total units per day, with possible closure days marked.
    daily = con.execute(
        "SELECT CAST(date AS DATE) AS day, SUM(sales) AS units FROM sales GROUP BY 1 ORDER BY 1"
    ).df()
    low = daily[daily["units"] < 0.1 * daily["units"].median()]
    fig, ax = plt.subplots(figsize=(11, 3.8))
    ax.plot(daily["day"], daily["units"], lw=0.8, color="#1f4e79")
    ax.scatter(low["day"], low["units"], color="#d62728", zorder=3, label="Possible closure day")
    ax.set_title(f"Total units sold per day - store {STORE}")
    ax.set_ylabel("Units")
    ax.legend(loc="upper left")
    fig.tight_layout()
    fig.savefig(FIGURES / "daily_sales.png", dpi=150)
    plt.close(fig)

    # Figure 2: share of zero-sales days by department (on-sale days only).
    zeros = con.execute("""
        SELECT dept_id, 100.0 * AVG(CASE WHEN sales = 0 THEN 1 ELSE 0 END) AS pct_zero
        FROM sales WHERE sell_price IS NOT NULL GROUP BY dept_id ORDER BY pct_zero
    """).df()
    fig, ax = plt.subplots(figsize=(7, 3.8))
    ax.barh(zeros["dept_id"], zeros["pct_zero"], color="#1f4e79")
    ax.set_xlabel("% of on-sale item-days with zero sales")
    ax.set_title("Intermittent demand by department")
    fig.tight_layout()
    fig.savefig(FIGURES / "zero_share_by_dept.png", dpi=150)
    plt.close(fig)

    report += ["## Figures", "",
               "![Daily sales](figures/daily_sales.png)", "",
               "![Zero sales by department](figures/zero_share_by_dept.png)", ""]
    out = REPORTS / "data_quality.md"
    out.write_text("\n".join(report), encoding="utf-8")
    print(f"\nReport written to {out}")


if __name__ == "__main__":
    main()
